// ============================================================================
// mosaic_remote_link -- work package I-028.
//
// The transport that carries one uop from its home cluster to a remote
// cluster's functional unit and brings the result back. It is a leaf: there is
// no consumer in the core yet, so the interior of the module is this file's
// decision, and every number in it is derived from a generated package.
//
// ------------------------------------------------------- what this module owns
//
// Three pieces of state, and nothing else:
//
//   1. `entry_valid/id/dst[0:ENTRIES-1]`  the *pairing table*: one entry per
//      request the link has taken responsibility for.
//   2. `req_pipe[0:LATENCY-1]`            the request hop, home  -> remote.
//   3. `rsp_pipe[0:LATENCY-1]`            the response hop, remote -> home.
//
// plus counters, so that the credit accounting is checkable from the `o_*`
// ports rather than only from the testbench's own model.
//
// ------------------------------------------------ why a pairing table, and its bound
//
// A response must be delivered to the *request that produced it*, and the
// link must be able to decide that without knowing anything about the core.
// So the link allocates its own name for each request -- a **link id**, the
// index of the entry it took -- and the request carries that name to the
// remote unit, which echoes it on the response. The table then answers the
// question in one step: `entry_valid[lid]` says whether the request that owns
// that name is still the link's responsibility.
//
// The link id alone is not enough, and the second half of the mechanism is why
// this module exists as a separate work package. A link id is an *index*, and
// an index is recycled: a killed request's entry is handed to the next request
// within a cycle or two, so a response that arrives late carries the link id of
// a request that has nothing to do with it. What makes that late response
// recognisable is the **identity** carried in the payload -- the uop's
// `{hart, rob_index, rob_gen, uop_index}` from `mosaic_id_pkg`, plus the
// destination `{tag, gen}`. The response is accepted only when the link id
// names a live entry *and* that entry's stored identity and destination are the
// ones the response carries. A response that fails either test is dropped and
// counted (`o_stale_rsp_ctr`), and the entry it named -- if any -- is untouched.
//
// This is the "tagged completion" shape the plan's I-002 contract requires: a
// wrapping index (the link id) is never the identity by itself, and the
// generation in the identity is what distinguishes the new occupant of a slot
// from the old one. It is the same rule `mosaic_rename` applies to a recycled
// physical tag, applied one level up.
//
// **Bound.** `ENTRIES = MOSAIC_IQ_ENTRIES` -- the depth of one cluster's issue
// queue. The justification is not "8 is a nice number": a remote request
// occupies a slot in the destination cluster's issue queue from the moment it
// is accepted until its result has left that cluster, so the number of requests
// one home cluster can have in flight to one remote cluster cannot exceed that
// queue's depth. Sizing the pairing table to exactly that bound means the link
// is never the *first* structure to run out of room: when the table is full,
// the destination queue is full too, and the back-pressure the home side sees
// is the one the far end would have applied anyway. It also fixes the width of
// the link id at `$clog2(ENTRIES)`, which is what makes the table a direct
// lookup rather than a search.
//
// ------------------------------------------------ the credit and what is conserved
//
// One table entry is one credit. A credit is taken when a request is accepted
// (`o_issued_ctr`) and returned exactly once when the entry is released, either
// because the response matched it (`o_matched_ctr`) or because the home side
// killed it (`o_killed_ctr`, which also covers the bulk `flush_valid`). The
// link therefore maintains
//
//     o_issued_ctr == o_returned_ctr + o_outstanding
//
// as an invariant of every cycle, reset included, and the counters are
// generated by the same events that move the table. `o_outstanding` is also
// registered *independently* of the bitmap, so the testbench can check both
// that the counter equals the population of `o_entry_valid` and that the
// conservation law holds -- a defect in either the table or the counter is
// visible without trusting the other.
//
// The returned credit is `o_returned_ctr = o_matched_ctr + o_killed_ctr`.
//
// A response that is dropped must also consume its credit, or the dropped
// response's entry would stay live forever: that is why a rejection is
// *counted* and not merely ignored. Only a response that is actually matched
// frees an entry, so a stale response cannot mask a live one.
//
// --------------------------------------------------------------- kill and flush
//
// `kill_valid` names one identity and `flush_valid` names all of them. Both are
// resolved against the pre-edge table, so a kill can never free an entry that a
// request is allocating in the same cycle (an allocation only ever considers an
// entry that is already invalid, and a freed entry is still valid until the
// edge). One cycle of extra back-pressure, in exchange for "released exactly
// once" being structural rather than argued.
//
// **A kill outranks a same-cycle response match for the same entry.** If both
// name the same entry, the home side has just told the link the uop is dead, so
// the response is dropped and counted like any other late response and the kill
// returns the credit. The alternative -- delivering a result for an instruction
// the home side has this cycle declared dead -- would make the home responsible
// for discarding it a second time, and would make "the killed request's
// resources are returned exactly once" depend on which of two simultaneous
// events the implementation happened to prefer.
//
// A kill does **not** withdraw the request from the network. The request may
// already have been handed to the remote unit, and a packet in flight cannot be
// recalled; the remote unit will do the work and answer, and the answer will be
// dropped as stale. That is what the case `remote.kill_with_delayed_response`
// exercises.
//
// -------------------------------------------------------- the two independent hops
//
// Each direction is its own registered pipeline of `LATENCY` stages, and the
// two share no payload storage, no valid/ready signal and no finite resource
// other than the credit table. `rem_req_valid` and `rsp_valid` are functions of
// registers alone (the link is a genuine registered hop in both directions);
// `req_ready` and `rem_rsp_ready` are the two ready signals, and each depends
// only on its own pipeline plus the far side of *its own* channel.
//
// The pipeline is a shift register with a **global stall**: the whole pipe
// advances by one stage each cycle unless its output stage holds an item the
// far side has not accepted. Two consequences are deliberate:
//
//   * The delay is a property of the link, not of the occupancy pattern: an
//     accepted request is offered to the remote end exactly `LATENCY` cycles
//     later, and every item in the pipe is delayed by the same stall. A
//     bubble-collapsing (fully elastic) pipeline would be cheaper in buffer
//     occupancy and would make the arrival time depend on the pattern of
//     bubbles in front of it, which is a property no consumer can use and no
//     test can state simply.
//   * Back-pressure from the far end is one gate deep ((`!full || ready`) from
//     `rem_req_ready` to `req_ready`), not a ripple through the pipe.
//
// `MOSAIC_REMOTE_LATENCY` is a real delay in the hardware and not a documented
// intention: the pipelines are `LATENCY` storage words each, and
// `MOSAIC_REMOTE_LINK_MUTANT_ONE_CYCLE` forces them to one stage so the
// testbench can show what a link that "always answers in one cycle" does.
//
// The design assumes a **minimum of one cycle in each direction**, and enforces
// it: `LATENCY` is clamped to at least 1, so a profile that set
// `MOSAIC_REMOTE_LATENCY` to 0 would get a one-cycle hop rather than a
// combinational path from the home cluster into the remote cluster's issue
// queue. A zero-stage pipeline is not a link.
//
// ------------------------------------------------------ no cycle between the channels
//
// The channels are separate, and the only resource they share is the credit
// table. That is enough to couple them transitively: a stalled home response
// port fills the response pipeline, which stops matches, which keeps entries
// live, which eventually refuses requests. The direction of that dependency is
// the point -- it is a chain and not a cycle:
//
//     rsp_ready -> rsp_pipe -> match -> entry free -> req_ready -> req_pipe -> rem_req_ready
//
// Nothing on the right-hand side feeds anything on the left. Progress flows one
// way: a request is only accepted if a credit is free, and a credit is only
// freed by a response (or a kill). Under the standard environment assumption --
// a side that is stalled eventually asserts its `ready`, and a side that has
// something to send eventually asserts its `valid` -- every cycle above
// terminates, so the link cannot deadlock and no request is lost.
//
// The card's fail criterion is the *opposite* arrangement: a request that is
// refused because the response path has a packet parked in it, with no causal
// chain to justify it. That is a shared buffer shared and nothing more, and
// `MOSAIC_REMOTE_LINK_MUTANT_SHARED_CHANNEL` is exactly that defect: it makes
// `req_ready` depend on the response pipeline being empty. The directed
// back-pressure phase asserts the property directly -- with the response path
// saturated and the table not full, a request must still be accepted -- so the
// mutant fails on a check that names the requirement rather than on a timeout.
//
// ------------------------------------------------------------- what is *not* here
//
//   * No functional unit. The link does not know what an opcode means; the
//     payload is opaque to it. The remote unit and its cluster's routing are
//     the consumer's business.
//   * No route field. One link instance serves exactly one home/remote cluster
//     pair, so the route is the instance's wiring and not a packet field. A
//     field the link could not check would be carried, stored and never
//     validated -- and the first thing it would hide is a mis-routed response.
//     I-029's steering decides *which* link a uop goes to; that decision happens
//     above this module.
//   * No epoch or generation of its own. The home side owns the identity,
//     including its generation, and the link compares identities bit for bit.
//   * No re-ordering. Responses are delivered in the order they arrive, which
//     is not necessarily the order the requests were issued; the link never
//     assumes the network is FIFO. That is why delivery is driven by the
//     response port and not by the request order.
//
// ------------------------------------------------------------- an assumption it makes
//
// The identity on the wire must be unique among the requests the home side has
// in flight *and* among the requests it has killed but whose response may still
// arrive. If the home re-issued a killed uop with the same identity, the old
// response would be indistinguishable from the new one -- not because the check
// is weak, but because the two packets would be carrying identical names. The
// generation in the identity is what the home side owns to prevent that; a
// re-issue must bump it. `remote.kill_with_delayed_response` tests the case as
// the card states it, with a *different* identity for the new request.
//
// ------------------------------------------------------------------ mutants
//
// `-DMOSAIC_REMOTE_LINK_MUTANT_*` injects one defect each; none is defined in
// the shipping build. The table with real output is in
// results/reports/I-028-remote-link.md.
// ============================================================================

